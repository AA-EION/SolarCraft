"""Generate crates/pv/src/spa_tables.rs from pvlib's SPA and Perez tables.

The periodic-term tables are from Reda & Andreas (2004), NREL/TP-560-34302,
as transcribed in pvlib-python (BSD-3-Clause, Copyright (c) 2023 pvlib python
Developers). Perez coefficients are from Perez et al. (1990), Solar Energy
44(5), 'allsitescomposite1990', as transcribed in pvlib.
Usage: python -I tools/gen_spa_tables.py > crates/pv/src/spa_tables.rs
"""
import numpy as np
import pvlib, pvlib.spa as s
from pvlib.irradiance import _get_perez_coefficients

def arr(name, a):
    rows = ",\n".join("    [" + ", ".join(repr(float(x)) for x in r) + "]" for r in a)
    return f"pub const {name}: [[f64; {a.shape[1]}]; {a.shape[0]}] = [\n{rows},\n];\n"

print("// @generated by tools/gen_spa_tables.py from pvlib", pvlib.__version__)
print("// Sources: Reda & Andreas (2004) NREL/TP-560-34302; Perez et al. (1990).")
print("// Transcription: pvlib-python, BSD-3-Clause, (c) pvlib python Developers.")
print("#![allow(clippy::all)]")
for n in ["L0","L1","L2","L3","L4","L5","B0","B1","R0","R1","R2","R3","R4","NUTATION_ABCD_ARRAY","NUTATION_YTERM_ARRAY"]:
    print(arr(n, np.asarray(getattr(s, n), dtype=float)))
f1, f2 = _get_perez_coefficients("allsitescomposite1990")
print(arr("PEREZ_F1", np.asarray(f1)))
print(arr("PEREZ_F2", np.asarray(f2)))
